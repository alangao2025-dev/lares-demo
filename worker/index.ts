import { Hono } from "hono";

type Env = { Bindings: CloudflareBindings };

interface Body { lang?: "en" | "zh"; code?: string; context?: string; images?: string[] }

const SYSTEM = (lang: "en" | "zh") => `You are the voice of LARES — "Classical Feng Shui for Modern Homes". Brand idea: "Every home has its guardians — your lares and penates."
You practice classical compass feng shui rooted in the I Ching (Eight Trigrams, Five Elements, Eight Mansions, annual flying stars, form school).

Task: write a short, warm, personalized note that ADDS to a reading already generated by our rules engine (its findings are in the context — do not repeat them at length, and never contradict the directions given; directions come only from the user's answers).
If photos are provided: briefly describe what you notice in each photo (layout, light, furniture placement, colors, clutter) and point out 1–3 additional gentle observations the questionnaire may have missed. If an answer seems to conflict with a photo, kindly suggest the user double-check it.
If no photos: write a personalized reflection based on the answers and focus areas.

Rules (strict):
- Gentle, encouraging, emotionally supportive. Start with something positive.
- Never use: bad luck, curse, danger, disaster, illness, death, poison arrow, killing energy, sha, evil, unlucky, "must". Say "energy that could use support", "an area to soften", "consider".
- Room directions: use ONLY the rooms and directions listed in the context. Never infer or assign a direction from a photo or floor plan; if something in a photo is not in the list, describe it without a direction.
- Never mention health, healing, sleep improvement, wealth gains or any other outcome as a result of a change; talk about how a space feels and what a piece traditionally symbolizes.
- Only suggest decor-level changes: moving furniture, lighting, colors, textiles, plants, decorative pieces, decluttering. Never suggest renovation or structural changes.
- Never promise results (no "will attract money", "cures", "guarantees"). Describe pieces only by traditional symbolism ("traditionally symbolizes…").
- Ground each observation in the I Ching briefly (trigram, element, or classical principle).
- Max ~280 words. Markdown with these headings: ${lang === "zh" ? "「照片里看到的」「补充的温和调整」「来自守护者的话」" : "“What I notice”, “A few more gentle shifts”, “A note from your guardians”"}.
- Write entirely in ${lang === "zh" ? "Simplified Chinese" : "American English"}.`;

const mediaType = (b64: string) => (b64.startsWith("iVBOR") ? "image/png" : b64.startsWith("R0lG") ? "image/gif" : b64.startsWith("UklG") ? "image/webp" : "image/jpeg");

const app = new Hono<Env>().basePath("/api");

app.get("/config", (c) => c.json({ ai: Boolean(c.env.LLM_API_KEY) }));

app.post("/insights", async (c) => {
  const env = c.env;
  if (!env.LLM_API_KEY) return c.json({ error: "AI is not configured on this demo." }, 503);
  const b = await c.req.json<Body>();
  if (env.ACCESS_CODE && b.code !== env.ACCESS_CODE) return c.json({ error: b.lang === "zh" ? "访问码不正确" : "Incorrect access code" }, 403);
  const lang = b.lang === "zh" ? "zh" : "en";
  const images = (b.images ?? []).slice(0, 6).filter((x) => typeof x === "string" && x.length < 1_500_000);
  const context = String(b.context ?? "").slice(0, 6000);

  const provider = env.LLM_PROVIDER === "openai" ? "openai" : "anthropic";
  const base = (env.LLM_BASE_URL || (provider === "openai" ? "https://api.openai.com/v1" : "https://api.anthropic.com")).replace(/\/+$/, "");
  const model = env.LLM_MODEL || (provider === "openai" ? "gpt-4o" : "claude-sonnet-5");
  let res: Response;
  if (provider === "anthropic") {
    const url = base.endsWith("/v1") ? `${base}/messages` : `${base}/v1/messages`;
    const payload = {
      model, max_tokens: 4000, stream: true, system: SYSTEM(lang),
      messages: [{ role: "user", content: [
        ...images.map((data) => ({ type: "image", source: { type: "base64", media_type: mediaType(data), data } })),
        { type: "text", text: context },
      ] }],
    };
    const headers = { "content-type": "application/json", "x-api-key": env.LLM_API_KEY, "anthropic-version": "2023-06-01" };
    res = await fetch(url, { method: "POST", headers, body: JSON.stringify({ ...payload, output_config: { effort: "low" } }) });
    if (res.status === 400) {
      const txt = await res.text();
      res = /output_config|effort/i.test(txt) ? await fetch(url, { method: "POST", headers, body: JSON.stringify(payload) }) : new Response(txt, { status: 400 });
    }
  } else {
    res = await fetch(`${base}/chat/completions`, {
      method: "POST", headers: { "content-type": "application/json", authorization: `Bearer ${env.LLM_API_KEY}` },
      body: JSON.stringify({ model, stream: true, max_tokens: 4000, messages: [
        { role: "system", content: SYSTEM(lang) },
        { role: "user", content: [...images.map((d) => ({ type: "image_url", image_url: { url: `data:${mediaType(d)};base64,${d}` } })), { type: "text", text: context }] },
      ] }),
    });
  }
  if (!res.ok || !res.body) return c.json({ error: `AI error ${res.status}: ${(await res.text()).slice(0, 300)}` }, 502);
  return new Response(res.body, { headers: { "content-type": "text/event-stream; charset=utf-8", "cache-control": "no-cache" } });
});

app.notFound((c) => c.json({ error: "Not Found" }, 404));
export default app;
